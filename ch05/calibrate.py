def split(total: int, keys: list[str], seed: str, pinned: dict[str, int]) -> dict[str, int]:
    """Split total tokens over keys by seeded weights, honouring pinned lengths."""
    rng = random.Random(seed)
    w = {k: rng.uniform(0.5, 1.5) for k in keys}
    free = [k for k in keys if k not in pinned]
    left = total - sum(pinned.values())
    raw = {k: left * w[k] / sum(w[f] for f in free) for k in free}
    out = {k: int(v) for k, v in raw.items()}
    for k in sorted(free, key=lambda k: out[k] - raw[k])[:left - sum(out.values())]:
        out[k] += 1
    return pinned | out


def doc(doc_id, version, kind, family, sections, total, jurisdiction="ALL",
        effective_from=None, effective_to=None, superseded_by=None, weight_seed=None):
    keys = [s[0] for s in sections]
    pinned = {k: n for (d, v, k), n in SPAN_TEXT.items() if (d, v) == (doc_id, version)}
    sizes = split(total, keys, weight_seed or f"{doc_id}|{version}", pinned)
    spans = []
    for s in sections:
        key, section, page = s[0], s[1], s[2]
        topic = s[3] if len(s) > 3 else None
        sid = f"{doc_id}@{version}#{key}"
        spans.append({"key": key, "section": section, "page": page, "topic": topic,
                      "tokens": sizes[key], "concl": CONCL_SPAN.get(sid, CONCL)})
    return {"doc_id": doc_id, "version": version, "kind": kind, "family": family,
            "jurisdiction": jurisdiction, "effective_from": effective_from,
            "effective_to": effective_to, "superseded_by": superseded_by, "spans": spans}


def build_docs() -> list[dict]:
    docs = []
    for fam, (secs, eds) in FORMS.items():
        for ver, eff in eds:   # editions share weights, so a section keeps its share
            docs.append(doc(fam, ver, "form", fam, secs, FORM_TEXT[(fam, ver)],
                            effective_from=eff, weight_seed=f"{fam}|form"))
    for d, ver, fam, topic, n in ENDORSEMENTS:
        secs = [(k, name, page, topic if k == "coverage" else None)
                for k, name, page in END_SECTIONS[:n]]
        docs.append(doc(d, ver, "endorsement", fam, secs, END_TEXT[(d, ver)],
                        effective_from=f"{ver}-01"))
    for d, ver, fam in AMENDATORY:   # state amendatory endorsements carry no governing topic
        for st in STATES:
            docs.append(doc(f"{d} {st}", ver, "endorsement", fam, END_SECTIONS,
                            AMD_TEXT[fam][st], jurisdiction=st, effective_from=f"{ver}-01"))
    for d, ver, st, topic, eff, to, sup in BULLETINS:
        secs = [(k, name, page, topic if k == "requirements" else None)
                for k, name, page in BULLETIN_SECTIONS]
        docs.append(doc(d, ver, "bulletin", "ALL", secs, BULLETIN_TEXT[d], jurisdiction=st,
                        effective_from=eff, effective_to=to, superseded_by=sup))
    return docs


